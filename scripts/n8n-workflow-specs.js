/**
 * Spec table consumed by generate-n8n-workflows.js. Kept as data (not
 * hand-written JSON) so all 27 workflows share one validated node/connection
 * skeleton — see that file for the shape every workflow is built into.
 *
 * `mainLogicComment` / httpRequest URLs describe calls into the dashboard's
 * INTERNAL API (apps/dashboard/src/app/api/internal/*), which is the only
 * place allowed to touch Postgres and the @barray/shared deterministic
 * engines. n8n orchestrates triggers, timing, retries and notifications; it
 * never re-implements scoring/calculation logic itself.
 */
const APP_URL = "={{ $env.APP_BASE_URL }}";

function httpMain(name, endpoint, bodyExpr) {
  return {
    mainNodeName: name,
    mainNodeType: "n8n-nodes-base.httpRequest",
    mainNodeTypeVersion: 4.2,
    mainNodeParameters: {
      method: "POST",
      url: `${APP_URL}${endpoint}`,
      authentication: "genericCredentialType",
      genericAuthType: "httpHeaderAuth",
      sendBody: true,
      specifyBody: "json",
      jsonBody: bodyExpr,
      options: {},
    },
    mainNodeCredentials: { httpHeaderAuth: { id: "PLACEHOLDER_DASHBOARD_API_CRED", name: "Barray Dashboard API" } },
    mainLogicNote: `Calls the internal dashboard API endpoint ${endpoint}, which applies deterministic @barray/shared logic and writes Postgres. n8n does not compute business rules itself.`,
    requiredCredentials: ["Barray Dashboard API (HTTP Header Auth)", "Barray Postgres"],
  };
}

